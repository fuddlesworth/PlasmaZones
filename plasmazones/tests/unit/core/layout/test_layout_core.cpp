    void testLayout_dirtyTracking_newLayoutIsClean()
    {
        // A freshly constructed layout is NOT dirty -- it has never been modified.
        // PhosphorZones::LayoutRegistry::addLayout() calls markDirty() explicitly when adding.
        PhosphorZones::Layout layout(QStringLiteral("Fresh"));
        QVERIFY(!layout.isDirty());
    }

    void testLayout_dirtyTracking_clearDirtyAfterSave()
    {
        PhosphorZones::Layout layout(QStringLiteral("Test"));
        layout.setName(QStringLiteral("Changed"));
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        QVERIFY(!layout.isDirty());
    }

    void testLayout_dirtyTracking_setterMarksDirty()
    {
        PhosphorZones::Layout layout(QStringLiteral("Test"));
        layout.clearDirty();
        QVERIFY(!layout.isDirty());

        layout.setName(QStringLiteral("NewName"));
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setDescription(QStringLiteral("desc"));
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setZonePadding(10);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setOuterGap(5);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setHiddenFromSelector(true);
        QVERIFY(layout.isDirty());

        // The remaining per-layout settings (now relocated to the sidecar on
        // save) must each mark the layout dirty, so an edit reaches saveLayout
        // and triggers the structural/settings split.
        layout.clearDirty();
        layout.setUsePerSideOuterGap(true);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setOuterGapTop(10);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setOuterGapBottom(11);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setOuterGapLeft(12);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setOuterGapRight(13);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setShowZoneNumbers(false);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setOverlayDisplayMode(1);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setAutoAssign(true);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setUseFullScreenGeometry(true);
        QVERIFY(layout.isDirty());

        // Aspect-ratio classification: an edit that fails to mark dirty
        // would skip saveLayout, the exact defect class this slot pins.
        layout.clearDirty();
        layout.setAspectRatioClass(::PhosphorLayout::AspectRatioClass::Ultrawide);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setMinAspectRatio(1.5);
        QVERIFY(layout.isDirty());

        layout.clearDirty();
        layout.setMaxAspectRatio(2.5);
        QVERIFY(layout.isDirty());

        // The three visibility allow-lists. Every setter above is generated by
        // the LAYOUT_SETTER macros, so none of them can lose its dirty mark
        // individually — these three are hand-written, which makes dropping
        // one emitModifiedIfNotBatched() a plausible single-line edit, and the
        // consequence is that a visibility change never reaches saveLayout.
        layout.clearDirty();
        layout.setAllowedScreens({QStringLiteral("DP-1")});
        QVERIFY2(layout.isDirty(), "setAllowedScreens did not mark the layout modified");

        layout.clearDirty();
        layout.setAllowedDesktops({2});
        QVERIFY2(layout.isDirty(), "setAllowedDesktops did not mark the layout modified");

        layout.clearDirty();
        layout.setAllowedActivities({QStringLiteral("{activity-uuid}")});
        QVERIFY2(layout.isDirty(), "setAllowedActivities did not mark the layout modified");

        // The fixed-geometry unit is hand-written too, and it notifies only on
        // a real change: setting the value it already holds is no edit.
        QSignalSpy unitSpy(&layout, &PhosphorZones::Layout::fixedGeometryInDevicePixelsChanged);
        layout.clearDirty();
        layout.setFixedGeometryInDevicePixels(true);
        QVERIFY2(layout.isDirty(), "setFixedGeometryInDevicePixels did not mark the layout modified");
        QCOMPARE(unitSpy.count(), 1);
        layout.clearDirty();
        layout.setFixedGeometryInDevicePixels(true);
        QVERIFY2(!layout.isDirty(), "setting the unit it already has marked the layout modified");
        QCOMPARE(unitSpy.count(), 1);
    }

